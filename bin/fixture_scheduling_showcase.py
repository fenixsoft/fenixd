def _git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True)


def _ensure_registered() -> None:
    """登记到全局注册表（带夹具标记）；失败仅告警（~ auto-scan 仍可发现该项目）。

    夹具项目须以 `fixture: true` 登记（fixture-project-governance）——读侧
    跨项目聚合据此跳过夹具告警噪音。流程：
      1. 先 `add_project(ROOT, fixture=True)`：新条目直接带标记写入；
      2. 若因条目已存在而跳过（存量条目无标记），改走 `mark_fixture` 补写标记；
      3. 任一步失败仅 WARN 不阻断（auto-scan 兜底可见性，标记缺失仅影响
         告警聚合过滤，由 spec 场景复位契约后续覆盖）。
    """
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
        from core.dashboard.registry import Registry

        added, msg = Registry().add_project(ROOT, fixture=True)
        if added:
            print(f"registry: added as fixture ({msg})")
            return
        # 条目已存在：显式补写夹具标记（存量条目无 fixture 键的场景）
        updated, upd_msg = Registry().mark_fixture(ROOT, fixture=True)
        print(f"registry: {'marked' if updated else 'present'} ({upd_msg})")
    except Exception as e:  # noqa: BLE001 注册失败不阻断 prepare
        print(f"WARN: registry 登记失败（依赖 auto-scan 兜底）: {e}", file=sys.stderr)


def _commit_baseline() -> bool:
    """建立夹具初始基线提交；返回是否成功（code-review item 06bfc79c4b04）。

    旧实现丢弃 `_git` 返回值，git 不可用/无可用身份/索引损坏时 `reset_fixture`
    仍打印「fixture created (fresh baseline commit)」并返回 0——prepare 报成功而
    夹具其实没有 HEAD，后续 daemon 的 `worktree add` 会在场景内失败，产生另一个
    难以定位的环境失败。此处显式检查 add/commit 的 returncode。
    """
    add = _git("add", "-A")
    if add.returncode != 0:
        print(f"FAIL: fixture git add 失败: {(add.stderr or '').strip()[:200]}", file=sys.stderr)
        return False
    commit = _git(
        "-c",
        "user.name=fenix-fixture",
        "-c",
        "user.email=fenix-fixture@localhost",
        "commit",
        "-qm",
        "fixture: scheduling-showcase 初始基线",
    )
    if commit.returncode != 0:
        print(
            f"FAIL: fixture git commit 失败（夹具将无 HEAD）: "
            f"{(commit.stderr or '').strip()[:200]}",
            file=sys.stderr,
        )
        return False
    return True


def _provision_from_template() -> None:
    """从仓内骨架补齐缺失的稳定资产（只补缺失，不覆盖，幂等）。

    骨架 = tests/fixtures/scheduling-showcase/ 下的调度包与测试/元数据；运行时
    场景会改写夹具的 .fenix/ 与 spec/，但从不碰这些资产，故「缺失即补」安全。
    README.md（骨架自述）与 conftest.py（pytest 收集排除，属 fenixd 测试侧）
    非夹具资产，不进运行时。
    """
    if not TEMPLATE.is_dir():
        print(f"WARN: 骨架目录不存在，跳过 provision: {TEMPLATE}", file=sys.stderr)
        return
    for src in TEMPLATE.rglob("*"):
        if not src.is_file():
            continue
        rel = src.relative_to(TEMPLATE)
        # 按文件名匹配（code-review item 769ce141db5b）：旧比较 rel.parts[0]
        # 只挡顶层 README.md/conftest.py，骨架中嵌套的 conftest.py（如
        # tests/conftest.py，pytest 收集 hook 的自然位置）会被拷入运行 fixture，
        # 与「把 pytest 收集文件挡在 fixture 外」的意图相悖。
        if rel.name in ("README.md", "conftest.py"):
            continue  # 骨架自述/收集排除文件，非运行时资产
        dst = ROOT / rel
        if dst.exists():
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def _reset_alerts_baseline() -> None:
    """把夹具 .fenix/admin_alerts.json 复位到空基线 `[]`（原子写）。

    fixture-project-governance：seed 场景经 AdminStore.append 往夹具写入的
    升级告警/处置记录是验证数据，若不清空会跨验证轮次永久累积（读侧跨项目
    聚合已跳过夹具，但显式查询与 `--status` 仍可见，复位保持基线一致）。

    写入 MUST 为原子写（同目录 tempfile.mkstemp + os.replace，与
    AdminStore._write_unlocked 同形态）——夹具 .fenix/ 内有常驻 daemon 与
    seed 场景的并发读-改-写，半写文件会被 AdminStore._read_unlocked 判为损坏
    并隔离改名，使后续 api 场景读到空集。MUST NOT 触碰 admin_alerts.json.lock
    （锁文件不属数据基线）。
    """
    alerts_path = ROOT / ".fenix" / "admin_alerts.json"
    alerts_path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path_str = tempfile.mkstemp(
        prefix=".admin_alerts.",
        suffix=".tmp",
        dir=str(alerts_path.parent),
    )
    tmp_path = Path(tmp_path_str)
    try:
        # fdopen 本身可能抛异常（如 fd 无效/编码问题）：此时 fd 仍未被接管，
        # finally 只 unlink 路径、不关 fd，会泄漏文件描述符。显式兜底关闭
        # （code-review item f056464f4cf7）。
        f = os.fdopen(fd, "w", encoding="utf-8")
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            tmp_path.unlink()
        except OSError:
            pass
        raise
    try:
        with f:
            json.dump([], f, ensure_ascii=False)
            f.write("\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(str(tmp_path), str(alerts_path))
    finally:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


def _atomic_write_text(path: Path, text: str) -> None:
    """原子写文本（tempfile + fsync + os.replace，同 _reset_alerts_baseline 惯用法）。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_str = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    tmp_path = Path(tmp_str)
    try:
        # fdopen 本身可能抛异常（如 fd 无效/编码问题）：此时 fd 仍未被接管，
        # finally 只 unlink 路径、不关 fd，会泄漏文件描述符（重复 --reset
        # 运行累积泄漏）。显式兜底关闭，镜像 _reset_alerts_baseline 的加固
        # （code-review item 804a6cf78f92）。
        f = os.fdopen(fd, "w", encoding="utf-8")
    except Exception:
        try:
            os.close(fd)
        except OSError:
            pass
        try:
            tmp_path.unlink()
        except OSError:
            pass
        raise
    try:
        with f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(str(tmp_path), str(path))
    finally:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


def _alerts_count() -> int:
    """读取夹具 admin_alerts.json 记录数；缺文件/损坏按 0（供 --status 只读核对）。"""
    alerts_path = ROOT / ".fenix" / "admin_alerts.json"
    try:
        data = json.loads(alerts_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return 0
    if not isinstance(data, list):
        return 0
    return sum(1 for e in data if isinstance(e, dict))


def reset_fixture() -> int:
    """重建/复位夹具；任何失败都返回非零 + 清晰 FAIL 信息。

    旧实现只对首个 mkdir 做异常处理，write_text / _reset_alerts_baseline /
    git 调用 / _ensure_registered 抛异常时以裸 traceback 中止，并留下**半复位**
    夹具（如 STATE.md 已复位而告警未复位、文件已写但无 git 基线），下一轮验证
    会把该状态当作合法基线（code-review item b8aa8f948be7）。故整段包进
    try/except，任何异常统一转成 FAIL + 非零退出。
    """
    try:
        return _reset_fixture_body()
    except Exception as e:  # noqa: BLE001 —— 统一转 FAIL，不留半复位状态
        print(f"FAIL: 夹具复位中止 {ROOT}: {type(e).__name__}: {e}", file=sys.stderr)
        return 1


def _reset_fixture_body() -> int:
    try:
        (ROOT / ".fenix").mkdir(parents=True, exist_ok=True)
    except OSError as e:
        print(f"FAIL: 无法创建夹具目录 {ROOT}: {e}", file=sys.stderr)
        return 1
    for name in SPEC_NAMES:
        (ROOT / "spec" / "changes" / name).mkdir(parents=True, exist_ok=True)

    # 稳定资产：缺失即从仓内骨架补齐（夹具丢失后重建的主路径）
    _provision_from_template()

    # 基线文件：无条件写回（场景每轮真实改写它们，且不再依赖夹具 git 历史——
    # 旧实现用 `git checkout HEAD -- STATE.md` 复位，丢历史后无 HEAD 可用，
    # 而 BASELINE_STATE 常量本就是权威基线）。
    # 原子写基线文件（code-review item 9904b83fe05e）：`write_text` 先截断后写，
    # 常驻的夹具 daemon（或并发的 seed/status 读取方）可能观测到零长度/半写的
    # STATE.md/config.yaml 而使 spec 状态断言失败——正是下方 _reset_alerts_baseline
    # 显式加固要防的形态。统一走同一原子写助手。
    _atomic_write_text(ROOT / ".fenix" / "STATE.md", BASELINE_STATE)
    _atomic_write_text(ROOT / ".fenix" / "config.yaml", BASELINE_CONFIG)

    # 告警基线：复位 admin_alerts.json 为空数组（fixture-project-governance 4.1）——
    # seed 写入的告警/处置记录是验证数据，不随 --reset 复位会跨验证轮次累积。
    _reset_alerts_baseline()

    # 夹具 daemon 的 worktree 管理需要 git；丢历史后此处首次 init（含基线提交，
    # 给 worktree add 一个 HEAD 可依）。已存在则不动历史，避免每轮 reset 产生
    # 提交churn——STATE.md 的复位靠上面的无条件写回，不再依赖 git。
    # 判定用 HEAD 实际存在（code-review item 0a5e888166c2）而非 .git 目录存在：
    # 上次运行可能已 init 而 _commit_baseline 失败（故意不留 HEAD），只看 .git
    # 会跳过基线提交、打印「fixture reset」返回 0——静默留下无 HEAD 夹具。
    if _git("rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
        init = _git("init", "-q")
        if init.returncode != 0:
            print(
                f"FAIL: fixture git init 失败: {(init.stderr or '').strip()[:200]}",
                file=sys.stderr,
            )
            return 1
        if not _commit_baseline():
            # 并发 reset 竞态：败者的 commit 因 nothing to commit 非零——
            # 此时 HEAD 已由胜者建好，本方视为成功而非 FAIL。
            if _git("rev-parse", "--verify", "--quiet", "HEAD").returncode == 0:
                print("fixture baseline already committed by concurrent reset")
            else:
                return 1
        print("fixture created (fresh baseline commit)")
    else:
        print("fixture reset (baseline files rewritten)")

    _ensure_registered()
    print(f"OK: {ROOT}（{len(SPEC_NAMES)} spec 夹具就绪）")
    return 0


def show_status() -> int:
    print(f"root: {ROOT} exists={ROOT.exists()}")
    print(f"git:  baseline={((ROOT / '.git').exists())}")
    if not ROOT.exists():
        return 0
    r = _git("status", "--porcelain")
    print(f"dirty:\n{r.stdout or '  (clean)'}")
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
        from core.dashboard.registry import Registry

        names = [p.get("name") for p in Registry().load().get("projects", [])]
        print(f"registered: {'scheduling-showcase' in names}")
    except Exception as e:  # noqa: BLE001
        print(f"registered: unknown ({e})")
    # 告警基线只读核对（fixture-project-governance 4.2）：复位后应为 0
    print(f"alerts:    {_alerts_count()} records（--reset 后应为 0）")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--reset", action="store_true", help="重建/复位夹具")
    group.add_argument("--status", action="store_true", help="只读查看夹具状态")
    args = parser.parse_args()
    return show_status() if args.status else reset_fixture()


if __name__ == "__main__":
    sys.exit(main())
