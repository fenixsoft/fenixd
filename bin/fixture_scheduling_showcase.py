def _spec_names_from_baseline() -> list:
    """从 BASELINE_STATE 解析 ``### <name>`` 头，得到 spec 名列表（保序）。

    单一事实源（code-review item d19cf40cdc47）：旧实现让 SPEC_NAMES 与
    BASELINE_STATE 各自列举同一批 8 个 spec，改一处漏一处会静默产生「有目录
    无状态条目」或反之，使冻结场景断言以难以定位的方式失败。现由 BASELINE_STATE
    派生，两者天然同步。
    """
    names = []
    for line in BASELINE_STATE.splitlines():
        if line.startswith("### "):
            names.append(line[len("### ") :].strip())
    return names


