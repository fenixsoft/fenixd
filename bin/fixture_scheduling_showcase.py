def _git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args],
                          capture_output=True, text=True)


def _ensure_registered() -> None:
    """登记到全局注册表；失败仅告警（~ auto-scan 仍可发现该项目）。"""
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
        from core.dashboard.registry import Registry
        added, msg = Registry().add_project(ROOT)
        print(f"registry: {'added' if added else 'present'} ({msg})")
    except Exception as e:  # noqa: BLE001 注册失败不阻断 prepare
        print(f"WARN: registry 登记失败（依赖 auto-scan 兜底）: {e}",
              file=sys.stderr)


def _commit_baseline() -> None:
    _git("add", "-A")
    _git("-c", "user.name=fenix-fixture",
         "-c", "user.email=fenix-fixture@localhost",
         "commit", "-qm", "fixture: scheduling-showcase 初始基线")


def reset_fixture() -> int:
    try:
        (ROOT / ".fenix").mkdir(parents=True, exist_ok=True)
    except OSError as e:
        print(f"FAIL: 无法创建夹具目录 {ROOT}: {e}", file=sys.stderr)
        return 1
    for name in SPEC_NAMES:
        (ROOT / "spec" / "changes" / name).mkdir(parents=True, exist_ok=True)

    state = ROOT / ".fenix" / "STATE.md"
    if not state.exists():
        state.write_text(BASELINE_STATE, encoding="utf-8")
    cfg = ROOT / ".fenix" / "config.yaml"
    if not cfg.exists():
        cfg.write_text(BASELINE_CONFIG, encoding="utf-8")

    if not (ROOT / ".git").exists():
        _git("init", "-q")
        _commit_baseline()
        print("fixture created (fresh baseline commit)")
    else:
        r = _git("checkout", "HEAD", "--", ".fenix/STATE.md")
        if r.returncode != 0:
            # 无基线提交（如 .git 损坏/空仓库）：重写基线并补提交
            state.write_text(BASELINE_STATE, encoding="utf-8")
            _commit_baseline()
            print("fixture reset (baseline rewritten)")
        else:
            print("fixture reset (git baseline)")

    _ensure_registered()
    print(f"OK: {ROOT}（8 spec 夹具就绪）")
    return 0


def show_status() -> int:
    print(f"root: {ROOT} exists={ROOT.exists()}")
    print(f"git:  baseline={((ROOT / '.git').exists())}")
    if not ROOT.exists():
        return 0
    r = _git("status", "--porcelain")
    print(f"dirty:\n{r.stdout or '  (clean)'}")
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
        from core.dashboard.registry import Registry
        names = [p.get("name") for p in Registry().load().get("projects", [])]
        print(f"registered: {'scheduling-showcase' in names}")
    except Exception as e:  # noqa: BLE001
        print(f"registered: unknown ({e})")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--reset", action="store_true", help="重建/复位夹具")
    group.add_argument("--status", action="store_true", help="只读查看夹具状态")
    args = parser.parse_args()
    return show_status() if args.status else reset_fixture()


if __name__ == "__main__":
    sys.exit(main())
